"""The flux of a small planet wholly inside the stellar disc as a series in its radius, with the switch that says where it may replace the closed form of velociraptor.analytic.

The flux removed by the planet is its area times the mean of the intensity I over its disc. For a function analytic on the disc, the mean over the disc of radius k centred at x is Pizzetti's series, the sum over n of
k^(2n) Laplacian^n I(x) / (4^n n! (n+1)!) (Pizzetti 1909; Evans, Partial Differential Equations, section 2.2 for the mean-value property it extends). With the quadratic law I(r) = 1 - u1 (1 - mu) - u2 (1 - mu)^2 and mu = sqrt(1 - r^2),
I = c0 + c1 mu + c2 mu^2 with c0 = 1 - u1 - u2, c1 = u1 + 2 u2 and c2 = -u2. The 2-d Laplacian of mu^m is m (m - 2) mu^(m-4) - m^2 mu^(m-2), so the Laplacian of mu^2 is -4 and every later one is zero. Laplacian^n of mu is (1 / mu) times a polynomial
in x = 1 / mu^2 with the integer coefficients of _series_terms.TERMS (generated by validation/generate_series_terms.py). The relative flux is 1 - k^2 mean / (1 - u1 / 3 - u2 / 6), the normalisation of velociraptor.analytic.

The term n of the flux is at most B_n = k^(2n+2) c1 |t|_n x^(2n-1) / (mu 4^n n! (n+1)!) over the normalisation, where |t|_n is the sum of the absolute values of the coefficients and x >= 1. A series to order N is used where B_(N+1) is at most
half the tolerance ABSOLUTE_FLUX_ERROR and B_(N+2) is at most half of B_(N+1), which bounds the tail by a geometric sum of ratio one half. The planet must also be wholly inside the disc (b + k < 1). The orders offered are ORDERS."""

import math

import numpy as np

from velociraptor._series_terms import ABSOLUTE, TERMS

ABSOLUTE_FLUX_ERROR = 1e-14  # bound on the truncation error of the flux
ORDERS = (3, 9)  # the orders of the series that the switch chooses from, lowest first
COEFFICIENT = {n: 1.0 / (4**n * math.factorial(n) * math.factorial(n + 1)) for n in range(13)}


def _polynomial(row, x):
    value = np.zeros_like(x)
    for t in reversed(row):
        value = value * x + float(t)
    return value


def series_flux(b, k, u1, u2, order=ORDERS[0]):
    """The relative flux for separation b and radius ratio k by the series to the given order in k^2; valid where `series_order` is at least that order."""
    b, k, u1, u2 = np.broadcast_arrays(*(np.asarray(v, dtype=float) for v in (b, k, u1, u2)))
    mu = np.sqrt(1 - b * b)
    x = 1.0 / (mu * mu)
    c1 = u1 + 2 * u2
    k2 = k * k
    mean = (1 - u1 - u2) + c1 * mu - u2 * mu * mu
    power = np.ones_like(k2)
    for n in range(1, order + 1):
        power = power * k2
        term = c1 * _polynomial(TERMS[n], x) / mu
        if n == 1:
            term = term - 4 * (-u2)
        mean = mean + COEFFICIENT[n] * power * term
    return 1 - k2 * mean / (1 - u1 / 3 - u2 / 6)


def _bound(n, k, c1, mu, normalisation):
    return COEFFICIENT[n] * k ** (2 * n + 2) * c1 * ABSOLUTE[n] * normalisation / mu ** (4 * n - 1)


def series_order(b, k, u1, u2):
    """The lowest order of ORDERS whose tail estimate is at most ABSOLUTE_FLUX_ERROR, or 0 where the closed form is to be used (the planet touches the limb, has no radius, or is too large for the series)."""
    b, k, u1, u2 = np.broadcast_arrays(*(np.asarray(v, dtype=float) for v in (b, k, u1, u2)))
    inside = (b + k < 1) & (k > 0)
    mu = np.sqrt(np.where(inside, 1 - b * b, 1.0))
    c1 = np.abs(u1) + 2 * np.abs(u2)
    normalisation = 1.0 / (1 - u1 / 3 - u2 / 6)
    order = np.zeros(b.shape, dtype=int)
    for n in reversed(ORDERS):
        first = _bound(n + 1, k, c1, mu, normalisation)
        second = _bound(n + 2, k, c1, mu, normalisation)
        order = np.where(inside & (first <= ABSOLUTE_FLUX_ERROR / 2) & (second <= first / 2), n, order)
    return order


def uses_series(b, k, u1, u2):
    """Where a series may replace the closed form."""
    return series_order(b, k, u1, u2) > 0
