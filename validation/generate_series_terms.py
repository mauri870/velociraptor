"""Writes src/velociraptor/_series_terms.py: the integer coefficients of the Laplacians of the limb-darkened intensity for the series of velociraptor.series.

With mu = sqrt(1 - r^2) the 2-d Laplacian of mu^m is m (m - 2) mu^(m-4) - m^2 mu^(m-2), so Laplacian^n of mu is a sum of odd powers of 1/mu with integer coefficients; written as (1 / mu) times a polynomial in x = 1 / mu^2 it is TERMS[n] = (t_0, ..., t_(2n-1)).
Run `python validation/generate_series_terms.py` to rewrite the module; tests/test_series.py holds the file equal to this output."""
from pathlib import Path

ORDER = 12  # the highest n tabulated; the coefficients are exact integers that pass 2^53 from n = 8 on, so a float64 constant rounds them by a relative 1e-16


def terms():
    """The coefficients of the n-th Laplacian of mu for n = 1 to ORDER, as (1 / mu) times a polynomial in x = 1 / mu^2: entry n is (t_0, ..., t_(2n-1)). The 2-d Laplacian of mu^m is m (m - 2) mu^(m-4) - m^2 mu^(m-2)."""
    poly = {1: 1}
    out = {}
    for n in range(1, ORDER + 1):
        new = {}
        for m, c in poly.items():
            new[m - 4] = new.get(m - 4, 0) + c * m * (m - 2)
            new[m - 2] = new.get(m - 2, 0) - c * m * m
        poly = {m: c for m, c in new.items() if c}
        out[n] = tuple(poly.get(-1 - 2 * q, 0) for q in range(2 * n))
    return out


def text():
    """The source of velociraptor/_series_terms.py: the table of terms() and the sum of the absolute values of each row."""
    lines = ['"""The integer coefficients of Laplacian^n of mu as (1 / mu) times a polynomial in x = 1 / mu^2, n = 1 to %d: TERMS[n] = (t_0, ..., t_(2n-1)), and ABSOLUTE[n] = the sum of their absolute values.' % ORDER,
             'Generated by validation/generate_series_terms.py; do not edit."""', "", "TERMS = {"]
    table = terms()
    for n, row in table.items():
        lines.append(f"    {n}: {row!r},")
    lines += ["}", "", "ABSOLUTE = {n: sum(abs(t) for t in row) for n, row in TERMS.items()}", ""]
    return "\n".join(lines)


def triton_text():
    """The Triton functions of the series of order 9 and of the switch between the orders 3 and 9, with the coefficients unrolled as float64 constants (a Python float in a kernel is float32)."""
    import math

    table = terms()
    coefficient = {n: 1.0 / (4**n * math.factorial(n) * math.factorial(n + 1)) for n in range(ORDER + 1)}
    absolute = {n: sum(abs(t) for t in row) for n, row in table.items()}
    out = ['"""The series of order 9 for a small planet wholly inside the disc and the switch between the series of orders 3 and 9, as Triton functions (velociraptor.series says what they compute).', 'Generated by validation/generate_series_terms.py; do not edit."""', "",
           "import triton", "import triton.language as tl", "", "", "@triton.jit", "def _series_high(b, k, u1, u2, normalisation):", "    mu = tl.sqrt(1 - b * b)", "    m1 = 1.0 / mu", "    x = m1 * m1", "    c1 = u1 + 2 * u2", "    k2 = k * k",
           "    mean = (1 - u1 - u2) + c1 * mu - u2 * mu * mu", "    power = k2"]
    for n in range(1, 10):
        row = table[n]
        expression = f"tl.full(b.shape, {float(row[-1])!r}, tl.float64)"
        for t in reversed(row[:-1]):
            expression = f"({expression}) * x + tl.full(b.shape, {float(t)!r}, tl.float64)"
        extra = " + 4 * u2" if n == 1 else ""
        out.append(f"    mean += tl.full(b.shape, {coefficient[n]!r}, tl.float64) * power * (c1 * ({expression}) * m1{extra})")
        out.append("    power = power * k2")
    out += ["    return 1 - k2 * mean * normalisation", "", "", "@triton.jit", "def _series_tier(b, k, u1, u2, normalisation, live, bound):",
            '    """Which orders the planet may use (small_low, small_high): the lowest order whose tail estimate is within `bound` (velociraptor.series.series_order)."""',
            "    mu2 = tl.maximum(tl.where(live, 1 - b * b, 1.0), tl.full(b.shape, 1e-300, tl.float64))", "    mu = tl.sqrt(mu2)", "    c1 = tl.abs(u1) + 2 * tl.abs(u2)", "    k2 = k * k", "    inside = live & (b + k < 1) & (k > 0)",
            "    half = tl.full(b.shape, 0.5, tl.float64)"]
    for name, n in (("low", 3), ("high", 9)):
        first, second = n + 1, n + 2
        ratio = (0.5 * coefficient[first] * absolute[first]) / (coefficient[second] * absolute[second])
        out.append(f"    # order {n}: the bound of the term {first} (k^{2 * first + 2} c1 |t| coefficient mu / mu2^{2 * first}) within the tolerance, and the term {second} at most half of it")
        out.append(f"    power_{name} = " + " * ".join(["k2"] * (first + 1)))
        out.append(f"    mu2_{name} = " + " * ".join(["mu2"] * (2 * first)))
        out.append(f"    small_{name} = inside & (tl.full(b.shape, {coefficient[first] * absolute[first]!r}, tl.float64) * power_{name} * c1 * normalisation * mu <= bound * mu2_{name}) & (k2 <= tl.full(b.shape, {ratio!r}, tl.float64) * mu2 * mu2)")
    out += ["    return small_low, small_high & ~small_low", ""]
    return "\n".join(out)


if __name__ == "__main__":
    root = Path(__file__).resolve().parent.parent / "src" / "velociraptor"
    (root / "_series_terms.py").write_text(text())
    (root / "_series_triton.py").write_text(triton_text())
